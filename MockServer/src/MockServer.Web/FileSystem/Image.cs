namespace MockServer.Web.FileSystem;

/// <summary>
/// GET /api/files/image — returns a placeholder image for file preview.
/// </summary>
public class Image : EndpointWithoutRequest
{
  public override void Configure()
  {
    Get("/files/image");
    AllowAnonymous();
  }

  public override async Task HandleAsync(CancellationToken ct)
  {
    var path = Query<string>("path") ?? "/";

    // Return a 1x1 transparent PNG as placeholder since no real files are stored
    byte[] transparentPng =
    [
      0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
      0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
      0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
      0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x62, 0x00, 0x00, 0x00, 0x02,
      0x00, 0x01, 0xE5, 0x27, 0xDE, 0xFC, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
      0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ];

    await SendBytesAsync(transparentPng, "image.png", "image/png", cancellation: ct);
  }
}
